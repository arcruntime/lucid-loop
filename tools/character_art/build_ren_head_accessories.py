def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write(name, value):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT/name).write_text(json.dumps(value, indent=2)+'\n', encoding='utf-8')


def signature(obj):
    mesh = obj.data
    result = {'matrix': [list(row) for row in obj.matrix_world]}
    for name, values, dtype in [
        ('vertices', [v.co[:] for v in mesh.vertices], '<f8'),
        ('loops', [v.vertex_index for v in mesh.loops], '<i4'),
        ('polygons', [(v.loop_start, v.loop_total, v.material_index) for v in mesh.polygons], '<i4'),
    ]:
        result[name] = hashlib.sha256(np.array(values, dtype=dtype).tobytes()).hexdigest()
    result['uv'] = {uv.name: hashlib.sha256(np.array([v.uv[:] for v in uv.data], dtype='<f8').tobytes()).hexdigest() for uv in mesh.uv_layers}
    result['shapes'] = {key.name: hashlib.sha256(np.array([v.co[:] for v in key.data], dtype='<f8').tobytes()).hexdigest() for key in mesh.shape_keys.key_blocks} if mesh.shape_keys else {}
    return result


def open_source():
    bpy.ops.wm.open_mainfile(filepath=str(SOURCE))
    return {obj.name: signature(obj) for obj in bpy.context.scene.objects if obj.type == 'MESH'}


def inspect():
    frozen = open_source()
    rows = []
    for obj in bpy.context.scene.objects:
        if obj.type != 'MESH': continue
        coords = np.array([obj.matrix_world@v.co for v in obj.data.vertices])
        rows.append({'name': obj.name, 'vertices': len(coords), 'bounds': [coords.min(axis=0).tolist(), coords.max(axis=0).tolist()], 'hidden': obj.hide_render, 'shapes': [(k.name,k.value) for k in obj.data.shape_keys.key_blocks] if obj.data.shape_keys else [], 'materials': [m.name for m in obj.data.materials]})
        if obj.name == 'Ren_Head':
            np.savez_compressed(OUT/'head-inspection-points.npz', world=coords)
    write('source-inspection.json', {'source': str(SOURCE.relative_to(ROOT)), 'source_sha256': digest(SOURCE), 'objects':rows, 'signatures': frozen})
    print(json.dumps(rows, indent=2), flush=True)


def material(name, srgb, roughness, metal=0):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    col = [v/12.92 if v <= .04045 else ((v+.055)/1.055)**2.4 for v in srgb]
    bsdf = mat.node_tree.nodes.get('Principled BSDF')
    bsdf.inputs['Base Color'].default_value = (*col, 1)
    bsdf.inputs['Roughness'].default_value = roughness
    bsdf.inputs['Metallic'].default_value = metal
    mat.diffuse_color = (*col,1)
    return mat


def cap_texture(mat):
    size = 1024
    yy, xx = np.mgrid[0:size,0:size]
    u, v = xx/(size-1), yy/(size-1)
    # Restrained woven-cloth grain, six-panel seam shading and short stitches.
    weave = .0018*(np.sin(xx*2.0)*np.sin(yy*1.7))
    noise = np.random.default_rng(713).normal(0,.0015,(size,size))
    panel = .009*np.cos(u*12*math.pi) + .005*np.sin(v*7)
    base = np.full((size,size), .070)+weave*.4+noise*.4+panel*.5
    crown = (v >= .12)&(v <= .76)
    seam_distance = abs(((u*6+.5)%1)-.5)/6
    base[crown&(seam_distance<.002)] -= .010
    base[crown&(seam_distance>.003)&(seam_distance<.0045)&((v*100)%1<.5)] += .018
    band = (v < .105)
    base[band] -= .012
    base[(abs(v-.125)<.0018)|(abs(v-.745)<.0018)] -= .008
    # Brim uses a distinct atlas strip. Curving is provided by real geometry.
    for row in [.79,.818,.848,.881,.918,.953]:
        base[abs(v-row)<.001] += .013
        base[(abs(v-row)<.00065)&((u*145)%1>.72)] -= .012
    rgb = np.stack((base*.95,base*.95,base*1.05),axis=-1)
    # Tiny irregular embroidered scratch mark, derived from the sheet's small
    # non-lettering emblem; it is not a copied brand or a fabricated word.
    def stroke(a,b,width,col):
        ax,ay=a;bx,by=b
        t=np.clip(((u-ax)*(bx-ax)+(v-ay)*(by-ay))/((bx-ax)**2+(by-ay)**2),0,1)
        d=(u-ax-t*(bx-ax))**2+(v-ay-t*(by-ay))**2
        rgb[d<width*width]=col
    for a,b in [((.928,.268),(.971,.292)),((.937,.25),(.956,.322)),((.947,.25),(.966,.311)),((.93,.29),(.976,.281))]:
        stroke(a,b,.00085,(.32,.32,.35))
    # Generated byte images save their supplied channel values. Keep the file
    # in sRGB; the image texture node performs the sRGB-to-linear conversion.
    rgba = np.dstack((rgb,np.ones((size,size))))
    image = bpy.data.images.new('Ren_Cap_Cloth_BaseColor',width=size,height=size,alpha=True)
    image.pixels.foreach_set(rgba.astype(np.float32).ravel())
    image.filepath_raw = str(OUT/'Ren_Cap_Cloth_BaseColor.png')
    image.file_format = 'PNG'
    image.save()
    # Reopen byte data so Blender, glTF and Unity all interpret the same sRGB
    # file. Generated-image pixels otherwise bypass the loaded image transform.
    bpy.data.images.remove(image)
    image = bpy.data.images.load(str(OUT/'Ren_Cap_Cloth_BaseColor.png'),check_existing=False)
    image.name = 'Ren_Cap_Cloth_BaseColor'
    image.pack()
    texture = mat.node_tree.nodes.new('ShaderNodeTexImage')
    texture.image = image
    mat.node_tree.links.new(texture.outputs['Color'],mat.node_tree.nodes.get('Principled BSDF').inputs['Base Color'])


class Builder:
    def __init__(self): self.vertices=[];self.faces=[];self.uv=[];self.materials=[]
    def vertex(self,p,uv=(0,0)):
        self.vertices.append(tuple(p));self.uv.append(tuple(uv));return len(self.vertices)-1
    def face(self,indices,mat=0):self.faces.append(tuple(indices));self.materials.append(mat)
    def object(self,name,mats,smooth=True):
        used=sorted({index for face in self.faces for index in face})
        remap={old:new for new,old in enumerate(used)}
        self.vertices=[self.vertices[index] for index in used]
        self.uv=[self.uv[index] for index in used]
        self.faces=[tuple(remap[index] for index in face) for face in self.faces]
        mesh=bpy.data.meshes.new(name+'_Mesh')
        mesh.from_pydata(self.vertices,[],self.faces)
        mesh.update()
        ob=bpy.data.objects.new(name,mesh)
        bpy.context.scene.collection.objects.link(ob)
        for mat in mats:mesh.materials.append(mat)
        for polygon,idx in zip(mesh.polygons,self.materials):polygon.material_index=idx;polygon.use_smooth=smooth
        uv=mesh.uv_layers.new(name='AccessoryUV')
        for loop in mesh.loops:uv.data[loop.index].uv=self.uv[loop.vertex_index]
        # Recalculate orientation without changing authored positions or UVs.
        import bmesh
        bm=bmesh.new();bm.from_mesh(mesh);bmesh.ops.recalc_face_normals(bm,faces=list(bm.faces));bm.to_mesh(mesh);bm.free()
        ob['bind_bone']='Head';ob['default_visible']=True;ob['source_reference']='art/characters/ren-model-sheet.png'
        return ob


CAP_CENTER = Vector((-.035,0,.19))
CAP_ROTATION = (Matrix.Rotation(math.radians(-7),3,'Z') @ Matrix.Rotation(math.radians(3),3,'X') @ Matrix.Rotation(math.radians(3),3,'Y'))


def cap_point(p):return CAP_CENTER+CAP_ROTATION@Vector(p)


def build_cap(cloth, underside):
    b=Builder(); n=28; rings=8
    # Open-bottom six-panel soft crown: geometry only where silhouette needs it.
    for j in range(rings):
        latitude=(j/rings)*math.pi/2
        for i in range(n+1):
            angle=2*math.pi*i/n
            panel=1+.014*math.cos(angle*6)*math.sin(latitude*2)+.005*math.sin(3*angle+latitude*5)
            back_distance=abs((angle-math.pi+math.pi)%(2*math.pi)-math.pi)
            opening=.065*max(0,1-(back_distance/.43)**2)**.5 if j==0 else 0
            asymmetry=math.sin(latitude)**2
            b.vertex(cap_point((.39*math.cos(latitude)*math.cos(angle)*panel-.012*asymmetry,.33*math.cos(latitude)*math.sin(angle)*panel+.007*asymmetry,.38*math.sin(latitude)+opening)), (i/n,.12+.64*j/rings))
    top=b.vertex(cap_point((-.012,.007,.38)),(.5,.76))
    for j in range(rings-1):
        for i in range(n):
            a=j*(n+1)+i;b.face((a,a+1,a+n+2,a+n+1))
    for i in range(n):b.face(((rings-1)*(n+1)+i,(rings-1)*(n+1)+i+1,top))
    # Narrow inside sweat band provides thickness at the visible lower edge.
    base=len(b.vertices)
    for j in range(3):
        for i in range(n+1):
            angle=2*math.pi*i/n
            rx,ry,z=[(.39,.33,0),(.386,.326,-.004),(.376,.316,.029)][j]
            b.vertex(cap_point((rx*math.cos(angle),ry*math.sin(angle),z)),(i/n,j*.045))
    for j in range(2):
        for i in range(n):
            middle=2*math.pi*(i+.5)/n
            if abs(middle-math.pi)<.43:continue
            a=base+j*(n+1)+i;b.face((a,a+1,a+n+2,a+n+1),1)
    # Rear adjustment strap below the real shallow arch opening.
    base=len(b.vertices)
    for z in (0,.018):
        for i in range(5):
            angle=math.pi-.45+.9*i/4
            b.vertex(cap_point((.393*math.cos(angle),.333*math.sin(angle),z)),(i/4,.03))
    for i in range(4):b.face((base+i,base+i+1,base+i+6,base+i+5))
    # Real curved bill, top and underside joined at outer/side boundaries.
    start=len(b.vertices);segments=28;rows=4
    for side in range(2):
        for j in range(rows):
            t=j/(rows-1)
            for i in range(segments+1):
                a=math.radians(-75+150*i/segments)
                x=(.39+.30*t)*math.cos(a)
                y=(.33+.022*t)*math.sin(a)
                z=-.038*t-.055*math.sin(a)**2*t+.003*math.sin(3*a)*t-(.004 if side else 0)
                b.vertex(cap_point((x,y,z)),(i/segments,.78+.19*t))
    slab=rows*(segments+1)
    for side in range(2):
        for j in range(rows-1):
            for i in range(segments):
                a=start+side*slab+j*(segments+1)+i
                b.face((a,a+1,a+segments+2,a+segments+1),side)
    for i in range(segments):
        a=start+(rows-1)*(segments+1)+i;b.face((a,a+1,a+1+slab,a+slab),1)
    for j in range(rows-1):
        for i in (0,segments):
            a=start+j*(segments+1)+i;b.face((a,a+segments+1,a+segments+1+slab,a+slab),1)
    # Low fabric-covered top button, integrated into the cap toggle.
    base=len(b.vertices)
    for j in range(2):
        for i in range(12):
            a=2*math.pi*i/12
            b.vertex(cap_point((-.012+.012*math.cos(a),.007+.012*math.sin(a),.38+j*.006)),(i/12,.05))
    for i in range(12):b.face((base+i,base+(i+1)%12,base+12+(i+1)%12,base+12+i))
    b.face(tuple(base+12+i for i in range(12)))
    return b.object('Ren_Cap',[cloth,underside])


def tube(builder, points, radius=.004, sides=4, closed=True, flat_width=None):
    start=len(builder.vertices);count=len(points)
    for i,p in enumerate(points):
        tangent=Vector(points[(i+1)%count])-Vector(points[(i-1)%count]) if closed else Vector(points[min(i+1,count-1)])-Vector(points[max(i-1,0)])
        tangent.normalize()
        ref=Vector((0,0,1)) if abs(tangent.z)<.8 else Vector((0,1,0))
        u=tangent.cross(ref).normalized();v=tangent.cross(u).normalized()
        for j in range(sides):
            a=2*math.pi*j/sides
            builder.vertex(Vector(p)+radius*math.cos(a)*u+(flat_width or radius)*math.sin(a)*v,(i/max(count-1,1),j/sides))
    for i in range(count if closed else count-1):
        for j in range(sides):builder.face((start+i*sides+j,start+i*sides+(j+1)%sides,start+((i+1)%count)*sides+(j+1)%sides,start+((i+1)%count)*sides+j))
    if not closed:
        builder.face(tuple(start+j for j in reversed(range(sides))))
        builder.face(tuple(start+(count-1)*sides+j for j in range(sides)))


def jewelry(silver,dark):
    b=Builder()
    # Paired narrow helix cuffs: main portrait's exposed anatomical right ear.
    for x,y,z,rx,ry in [(-.118,-.307,.108,.013,.019),(-.129,-.316,.080,.013,.019)]:
        points=[(x+rx*math.cos(a),y+ry*math.sin(a),z) for a in np.linspace(math.radians(-25),math.radians(270),13)]
        tube(b,points,.0038,4,False,flat_width=.005)
    cuff=b.object('Ren_RightEar_HelixCuffs',[silver])
    # A small lobe hoop, angled transverse link and slim open drop frame.
    b=Builder()
    points=[(-.057+.013*math.cos(a),-.294,-.030+.019*math.sin(a)) for a in np.linspace(0,2*math.pi,12,endpoint=False)]
    tube(b,points,.0037,4,True)
    tube(b,[(-.073,-.310,-.035),(-.040,-.313,-.022)],.005,4,False)
    top=Vector((-.059,-.313,-.051))
    profile=[(-.011,0),(.011,0),(.012,-.085),(.005,-.104),(-.005,-.104),(-.012,-.085)]
    tube(b,[(top.x+dx,top.y,top.z+dz) for dx,dz in profile],.0032,4,True)
    drop=b.object('Ren_RightEar_DropPiercing',[silver])
    return [cuff,drop]



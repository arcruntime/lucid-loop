    report={'source_head_sha256':digest(SOURCE),'geometry_built_from':'original Ren designer sheet; local Blender mesh construction, no paid model call','objects':{name:{k:v for k,v in row.items() if k!='world'} for name,row in source.items()},'roundtrips':{}}
    for suffix in ('glb','fbx'):
        bpy.ops.wm.read_factory_settings(use_empty=True)
        path=OUT/('Ren_Head_Accessories.'+suffix)
        if suffix=='glb':bpy.ops.import_scene.gltf(filepath=str(path))
        else:bpy.ops.import_scene.fbx(filepath=str(path),use_anim=False,automatic_bone_orientation=False)
        bpy.context.view_layer.update()
        meshes=[obj for obj in bpy.context.scene.objects if obj.type=='MESH']
        assert {obj.name for obj in meshes}==set(source)
        checks={}
        for obj in meshes:
            obj.data.calc_loop_triangles()
            world=np.array([obj.matrix_world@v.co for v in obj.data.vertices])
            original=source[obj.name]['world']
            distance=np.linalg.norm(world[:,None,:]-original[None,:,:],axis=2)
            error=float(max(distance.min(0).max(),distance.min(1).max()))
            checks[obj.name]={'triangles':len(obj.data.loop_triangles),'render_vertices':len(world),'nearest_vertex_error_native_units':error,'uv_layer_count':len(obj.data.uv_layers),'materials':[mat.name for mat in obj.data.materials]}
            if not (checks[obj.name]['triangles']==source[obj.name]['triangles'] and error<2e-6 and len(obj.data.uv_layers)>=1):
                raise RuntimeError(json.dumps({'format':suffix,'name':obj.name,'actual':checks[obj.name],'expected_triangles':source[obj.name]['triangles']}))
        report['roundtrips'][suffix]={'sha256':digest(path),'objects':checks,'no_armatures':not any(obj.type=='ARMATURE' for obj in bpy.context.scene.objects)}
    report['blend_sha256']=digest(OUT/'Ren_Head_Accessories.blend')
    report['texture_sha256']=digest(OUT/texture_name)
    report['units']='Unnormalized native head units; error values are not world metres.'
    import struct
    data=(OUT/'Ren_Head_Accessories.glb').read_bytes()
    json_size=struct.unpack_from('<I',data,12)[0]
    gltf=json.loads(data[20:20+json_size]);binary=data[28+json_size:]
    view=gltf['bufferViews'][gltf['images'][0]['bufferView']]
    png=binary[view.get('byteOffset',0):view.get('byteOffset',0)+view['byteLength']]
    assert hashlib.sha256(png).hexdigest()==report['texture_sha256']
    report['embedded_glb_texture_exact_png']=True
    report['gltf_materials']=[{'name':m['name'],'double_sided':m.get('doubleSided',False),'pbr':m.get('pbrMetallicRoughness'),'extensions':m.get('extensions',{})} for m in gltf['materials']]
    report['total_accessory_triangles']=sum(row['triangles'] for row in source.values())
    report['limitations']=['Native head units remain unchanged; a later common character normalization is required.','Roundtrips verify static placement/topology/material slots/UV presence, not Unity shader appearance.','No rig or skin weights; all objects provide Head bind metadata.']
    write('export-verification.json',report)
    print('REN_ACCESSORIES_EXPORT_VERIFIED',report['total_accessory_triangles'],flush=True)


